<script setup>
import { computed } from 'vue';
import { Link } from '@inertiajs/vue3';

const props = defineProps({
    href: {
        type: String,
        required: true,
    },
    active: {
        type: Boolean,
    },
});

const classes = computed(() =>
    props.active
        ? 'inline-flex items-center px-1 pt-1 ts-nav-active text-sm font-semibold leading-5 focus:outline-none transition duration-150 ease-in-out'
        : 'inline-flex items-center px-1 pt-1 ts-nav-inactive text-sm font-medium leading-5 focus:outline-none transition duration-150 ease-in-out',
);
</script>

<template>
    <Link :href="href" :class="classes">
        <slot />
    </Link>
</template>
